# Variables and basic math
name = "Python"
num1 = 10
num2 = 5
sum_result = num1 + num2

# String formatting
print(f"Welcome to {num1} + {num2} in {name}!")
print(f"The total sum is: {sum_result}")

# Conditional statement
if sum_result > 10:
    print("The sum is greater than 10.")
else:
    print("The sum is 10 or less.")
